"""Build references/export-index.md from whip_core's LuaLS stubs and check it against real exports() calls.

Usage: python -I export_index.py <path-to-whip_core> <output.md>
Reads only; stdlib only.
"""
import glob
import os
import re
import sys

PIPE = '│'  # box-drawing bar: keeps a type union readable inside a Markdown table cell


def cell(text, limit):
    text = text.replace('|', PIPE)
    return text if len(text) <= limit else text[:limit - 1] + '…'


def parse_stub(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    res, section, block = [], 'General', []
    for i, ln in enumerate(lines):
        m = re.match(r'^-- ([A-Z][^=]{1,60})$', ln)
        if m and i > 0 and lines[i - 1].startswith('-- ===='):
            section, block = m.group(1).strip(), []
            continue
        if ln.startswith('---'):
            block.append(ln)
            continue
        m = re.match(r'^function whip_core:(\w+)\((.*?)\)\s*end', ln)
        if m:
            name, params = m.groups()
            doc = [b[3:].strip() for b in block if not b.startswith('---@')]
            desc = next((d for d in doc if d and not d.startswith(('exports.', 'local ', '|', "'", '{', '--', 'Whip.'))), '')
            asy = any(b.startswith('---@async') for b in block)
            ptypes = {}
            for b in block:
                pm = re.match(r'---@param (\w+)(\??) (.*)$', b)
                if pm:
                    ty, depth = '', 0
                    for ch in pm.group(3):  # the type runs to the first space outside braces/parens
                        if ch in '{(<': depth += 1
                        elif ch in '})>': depth -= 1
                        elif ch == ' ' and depth == 0: break
                        ty += ch
                    ptypes[pm.group(1)] = pm.group(2) == '?' or ty.endswith(('|nil', '?')) or ty.startswith('nil|')
            ps = [p + ('?' if ptypes.get(p) else '') for p in (x.strip() for x in params.split(',')) if p]
            rets = [re.sub(r'^---@return\s+', '', b) for b in block if b.startswith('---@return')]
            res.append(dict(name=name, params=', '.join(ps), section=section, desc=desc, asy=asy,
                            ret='; '.join(rets)))
            block = []
            continue
        if not ln.strip() or not ln.startswith('--'):
            block = []
    return res


def real_exports(core):
    real = {'server': set(), 'client': set(), 'shared': set()}
    for f in glob.glob(os.path.join(core, '**', '*.lua'), recursive=True):
        rel = os.path.relpath(f, core).replace(os.sep, '/')
        if rel.startswith(('types/', 'dev/', 'docs/')):
            continue
        side = ('server' if rel.startswith('server/') else
                'client' if rel.startswith(('client/', 'tools/')) else 'shared')
        text = re.sub(r'(?m)^[ \t]*--.*$', '', open(f, encoding='utf-8', errors='ignore').read())  # skip comment lines
        real[side].update(re.findall(r"exports\(\s*['\"](\w+)['\"]", text))
    return real


def table(items, side, realset):
    out, cur = [], None
    for it in items:
        if it['section'] != cur:
            cur = it['section']
            out.append(f"\n### {side}: {cur}\n\n| Export | Waits | Returns | What |\n|---|---|---|---|")
        flag = '' if it['name'] in realset else ' (no `exports()` call found)'
        out.append(f"| `{it['name']}({it['params']})`{flag} | {'WAITS' if it['asy'] else ''} | "
                   f"{cell(it['ret'], 140)} | {cell(it['desc'], 170)} |")
    return '\n'.join(out)


def main():
    core, out = sys.argv[1], sys.argv[2]
    srv = parse_stub(os.path.join(core, 'types', 'server.lua'))
    cli = parse_stub(os.path.join(core, 'types', 'client.lua'))
    real = real_exports(core)
    rs, rc = real['server'] | real['shared'], real['client'] | real['shared']
    sn, cn = {i['name'] for i in srv}, {i['name'] for i in cli}
    miss_s = sorted(n for n in rs - sn - cn if not n.startswith('__Test'))
    miss_c = sorted(n for n in rc - cn - sn)
    hdr = f"""# whip_core export index

Every export in whip_core's LuaLS stubs (`whip_core/types/server.lua`, `types/client.lua`), grouped as the
stubs group them: its parameters (`?` = optional), WAITS when the stub marks it `---@async` (call it from a
thread or handler, never at file scope), the return annotation and the stub's first line. Type unions use
`{PIPE}` in place of `|` so the table stays readable.

Generated by `scripts/export_index.py` from whip_core commit d12235f (2026-11-14). Regenerate after a WHIP
update. Use this file to check that a name exists and which side it is on; read the topic reference for
options, defaults and behaviour.

Counts: {len(srv)} server stubs, {len(cli)} client stubs. `exports('…')` registrations found in source:
{len(rs)} server or shared, {len(rc)} client or shared.

## Contents
- Server exports (by section)
- Client exports (by section)
- Registered but not in the stubs
"""
    body = "\n## Server exports\n" + table(srv, 'Server', rs)
    body += "\n\n## Client exports\n" + table(cli, 'Client', rc)
    body += ("\n\n## Registered but not in the stubs\n\nServer or shared (`__Test*` seams excluded): "
             + (', '.join(f'`{n}`' for n in miss_s) or 'none')
             + "\n\nClient or shared: " + (', '.join(f'`{n}`' for n in miss_c) or 'none')
             + "\n\nThese exist at run time but have no stub, so the editor will not offer them. Read the "
               "registering file before relying on one: some are internal.\n")
    open(out, 'w', encoding='utf-8').write(hdr + body)
    print('server stubs', len(srv), 'client stubs', len(cli), 'real srv', len(rs), 'real cli', len(rc))
    print('stub without exports():', [i['name'] for i in srv if i['name'] not in rs],
          [i['name'] for i in cli if i['name'] not in rc])
    print('registered without stub:', miss_s, miss_c)


if __name__ == '__main__':
    main()
